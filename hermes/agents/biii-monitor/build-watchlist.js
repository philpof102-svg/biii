'use strict';
/**
 * build-watchlist.js — regenerate the sentinel's address book FROM THE CHAIN, never by hand.
 * ==========================================================================================
 * The watchlist this replaces carried three addresses that were 41 characters long: silently malformed, so
 * the sentinel had been scanning nothing for them since the day it was written, while still reporting "no
 * change" like everything was fine. A hand-maintained list of hex strings degrades exactly that way — one
 * dropped character and a watcher goes quietly blind.
 *
 * So the book is generated: real Base tokens are taken from the chain's own busiest pools (GeckoTerminal, by
 * 24h volume) and the known-bad side comes from our curated dataset. Every entry is shape-validated before it
 * is written, and anything malformed aborts the write rather than landing in the file.
 */
const fs = require('node:fs');
const path = require('node:path');
const https = require('node:https');

const OUT = path.join(__dirname, 'watchlist.json');
const KNOWN_BAD = path.join(__dirname, '..', '..', '..', 'data', 'known-bad.json');
const PAGES = 4;                 // 20 pools per page
const MIN_LIQ = 250000;          // a "major" worth watching, not a fresh launch (token-radar covers those)
const MAX_TOKENS = 40;
const MAX_BAD = 25;              // a sample of the denylist; the full set lives in known-bad.json
const isAddr = (a) => /^0x[0-9a-fA-F]{40}$/.test(a);

// Quote assets sit on the other side of nearly every pool; they are infrastructure, not watch targets.
const QUOTES = new Set(['0x4200000000000000000000000000000000000006', '0x833589fcd6edb6e08f4c7c32d4f71b54bda02913']);

const getJSON = (url) => new Promise((resolve) => {
  https.get(url, { headers: { accept: 'application/json' } }, (res) => {
    let d = ''; res.on('data', (c) => (d += c));
    res.on('end', () => { try { resolve(JSON.parse(d)); } catch { resolve(null); } });
  }).on('error', () => resolve(null));
});

(async () => {
  const byAddr = {};
  for (let p = 1; p <= PAGES; p++) {
    const j = await getJSON('https://api.geckoterminal.com/api/v2/networks/base/pools?sort=h24_volume_usd_desc&page=' + p);
    for (const pool of ((j && j.data) || [])) {
      const a = pool.attributes || {};
      const id = ((((pool.relationships || {}).base_token || {}).data) || {}).id || '';
      const addr = (id.split('_')[1] || '').toLowerCase();
      const liq = parseFloat(a.reserve_in_usd) || 0;
      if (!isAddr(addr) || QUOTES.has(addr) || liq < MIN_LIQ) continue;
      const sym = String(a.name || '').split('/')[0].trim().toUpperCase();
      if (!sym || byAddr[addr]) continue;
      byAddr[addr] = { address: addr, claimedSymbol: sym, liquidityUsd: Math.round(liq) };
    }
    await new Promise((r) => setTimeout(r, 300));   // be polite to a free API
  }

  const tokens = Object.values(byAddr).sort((x, y) => y.liquidityUsd - x.liquidityUsd).slice(0, MAX_TOKENS)
    .map((t) => ({ address: t.address, claimedSymbol: t.claimedSymbol, claimedIssuer: t.claimedSymbol, liquidityUsd: t.liquidityUsd }));

  let bad = [];
  try {
    const kb = JSON.parse(fs.readFileSync(KNOWN_BAD, 'utf8'));
    const src = Array.isArray(kb.addresses) ? kb.addresses : Object.keys(kb.addresses || {});
    bad = src.filter(isAddr).slice(0, MAX_BAD);
  } catch { /* the denylist is optional here; the sentinel reads the full file at runtime anyway */ }

  const malformed = [...tokens.map((t) => t.address), ...bad].filter((a) => !isAddr(a));
  if (malformed.length) { console.error('ABORT — refusing to write malformed addresses:', malformed); process.exit(1); }
  if (!tokens.length) { console.error('ABORT — no tokens resolved; leaving the existing watchlist untouched'); process.exit(1); }

  fs.writeFileSync(OUT, JSON.stringify({
    _note: 'GENERATED by build-watchlist.js — do not hand-edit. Tokens are the busiest Base pools resolved live from the chain; every address is shape-validated before write (the previous hand-written list had 41-character addresses the sentinel silently failed on). Known-bad here is a SAMPLE for scan coverage; the authoritative denylist is data/known-bad.json.',
    generatedAt: new Date().toISOString(),
    source: 'geckoterminal base pools by 24h volume, liquidity >= $' + MIN_LIQ.toLocaleString('en-US'),
    addresses: bad, tokens,
  }, null, 2) + '\n');

  console.log('watchlist rebuilt: ' + tokens.length + ' tokens + ' + bad.length + ' known-bad addresses, all well-formed');
  console.log('top: ' + tokens.slice(0, 8).map((t) => t.claimedSymbol + ' $' + Math.round(t.liquidityUsd / 1000) + 'k').join(' · '));
})();
